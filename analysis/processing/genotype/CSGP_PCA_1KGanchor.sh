# cp Impute/Imputed/GDA01_MEGA2_5-postHWE-removeRepeatInd-updated.* .

qcdir='/data/abattle4/taiboli/ICC/Genotype/CGSPLL240202/Merged/'
name='CGSP_GDA01_MEGA2_5-postHWE-removeRepeatInd'

refdir='/home/tli64/data-abattle4/taiboli/ICC/ICC/1KGReference/plinkQC/'
refname='all_phase3'
outdir='/data/abattle4/taiboli/ICC/Genotype/CGSPLL240202/Merged/Merge1KG/'


${plinkExc} --bfile $qcdir/$name --recode --out $qcdir/$name

liftoverdir='/home/tli64/data-abattle4/taiboli/ICC/ICC/1KGReference/plinkQC/liftOverPlink/'

### Reference: liftoverplink https://github.com/sritchie73/liftOverPlink
### additional reference: https://www.biostars.org/p/252938/
### There is a bug in the code - so need to manually run liftover tool
#$refdir/liftOver MEGA234-Merged-updated.map.bed $refdir/hg38ToHg19.over.chain.gz MEGA234-Merged-updated_liftedHg19.bed MEGA234-Merged-updated_liftedHg19.bed.unlifted
python2 $liftoverdir/liftOverPlink.py --map $qcdir/${name}.map --out $qcdir/${name}_liftedHg19 --chain $refdir/hg38ToHg19.over.chain.gz --bin $refdir/liftOver

python2 $liftoverdir/rmBadLifts.py --map $qcdir/${name}_liftedHg19.map --out good_lifted.map --log bad_lifted.dat
cut -f 2 bad_lifted.dat > to_exclude.dat
cut -f 4 ${name}_liftedHg19.bed.unlifted | sed "/^#/d" >> to_exclude.dat

# Note: this will clobber the lifted MAP file generated by `liftOverPlink`:
${plinkExc} --file ${name} --recode --out ${name}_liftedHg19 --exclude bad_lifted.dat
${plinkExc} --file ${name}_liftedHg19 --recode --make-bed --out ${name}_finalLiftedHg19


name=${name}'_finalLiftedHg19'
mkdir $qcdir/plink_log/

### follow plinkQC
### https://meyer-lab-cshl.github.io/plinkQC/articles/AncestryCheck.html
### Filter reference and data
awk 'BEGIN {OFS="\t"}  ($5$6 == "GC" || $5$6 == "CG" \
                        || $5$6 == "AT" || $5$6 == "TA")  {print $2}' \
    $qcdir/$name.bim  > \
    $outdir/$name.ac_gt_snps

### No need to repeat this step 
# awk 'BEGIN {OFS="\t"}  ($5$6 == "GC" || $5$6 == "CG" \
#                         || $5$6 == "AT" || $5$6 == "TA")  {print $2}' \
#     $refdir/$refname.bim  > \
#     $refdir/$refname.ac_gt_snps

${plinkExc} --bfile  $qcdir/$name \
      --exclude $outdir/$name.ac_gt_snps \
      --make-bed \
      --out $outdir/$name.no_ac_gt_snps
mv  $outdir/$name.no_ac_gt_snps.log $qcdir/plink_log/$name.no_ac_gt_snps.log


######### Pruning
cp /home/tli64/data-abattle4/taiboli/ICC/ICC/1KGReference/MEGA234//high-LD-regions.bed .

${plinkExc} --bfile  $outdir/$name.no_ac_gt_snps \
      --exclude range $qcdir/high-LD-regions.bed  \
      --indep-pairwise 50 5 0.2 \
      --out $outdir/$name.no_ac_gt_snps
mv  $outdir/$name.no_ac_gt_snps.log $qcdir/plink_log/$name.prune.log

${plinkExc}  --bfile  $outdir/$name.no_ac_gt_snps \
      --extract $outdir/$name.no_ac_gt_snps.prune.in \
      --make-bed \
      --out $outdir/$name.pruned
mv  $outdir/$name.pruned.log $qcdir/plink_log/$name.pruned.log



#### Filter reference dataset
${plinkExc} --bfile  $refdir/$refname \
      --extract $outdir/$name.no_ac_gt_snps.prune.in \
      --allow-extra-chr \
      --make-bed \
      --out $outdir/$refname.pruned
mv  $outdir/$refname.pruned.log $qcdir/plink_log/$refname.pruned.log


### check and correct chromosome mismatch
awk 'BEGIN {OFS="\t"} FNR==NR {a[$2]=$1; next} \
    ($2 in a && a[$2] != $1)  {print a[$2],$2}' \
    $outdir/$name.pruned.bim $outdir/$refname.pruned.bim | \
    sed -n '/^[XY]/!p' > $outdir/$refname.toUpdateChr

${plinkExc} --bfile $outdir/$refname.pruned \
      --update-chr $outdir/$refname.toUpdateChr 1 2 \
      --make-bed \
      --out $outdir/$refname.updateChr
mv $outdir/$refname.updateChr.log $qcdir/plink_log/$refname.updateChr.log

### Position mismatch
awk 'BEGIN {OFS="\t"} FNR==NR {a[$2]=$4; next} \
    ($2 in a && a[$2] != $4)  {print a[$2],$2}' \
    $outdir/$name.pruned.bim $outdir/$refname.pruned.bim > \
    $outdir/${refname}.toUpdatePos

### Possible allele flips
awk 'BEGIN {OFS="\t"} FNR==NR {a[$1$2$4]=$5$6; next} \
    ($1$2$4 in a && a[$1$2$4] != $5$6 && a[$1$2$4] != $6$5)  {print $2}' \
    $outdir/$name.pruned.bim $outdir/$refname.pruned.bim > \
    $outdir/$refname.toFlip


### Update position and flip alleles
${plinkExc} --bfile $outdir/$refname.updateChr \
      --update-map $outdir/$refname.toUpdatePos 1 2 \
      --flip $outdir/$refname.toFlip \
      --make-bed \
      --out $outdir/$refname.flipped
mv $outdir/$refname.flipped.log $qcdir/plink_log/$refname.flipped.log

### Remove mismatches
awk 'BEGIN {OFS="\t"} FNR==NR {a[$1$2$4]=$5$6; next} \
    ($1$2$4 in a && a[$1$2$4] != $5$6 && a[$1$2$4] != $6$5) {print $2}' \
    $outdir/$name.pruned.bim $outdir/$refname.flipped.bim > \
    $outdir/$refname.mismatch

${plinkExc} --bfile $outdir/$refname.flipped \
      --exclude $outdir/$refname.mismatch \
      --make-bed \
      --out $outdir/$refname.clean
mv $outdir/$refname.clean.log $qcdir/plink_log/$refname.clean.log

###################################
## Merge
###################################
${plinkExc} --bfile $outdir/$name.pruned  \
      --bmerge $outdir/$refname.clean.bed $outdir/$refname.clean.bim \
         $outdir/$refname.clean.fam  \
      --make-bed \
      --out $outdir/$name.merge.$refname
mv $outdir/$name.merge.$refname.log $qcdir/plink_log


###################################
## PCA
###################################

${plinkExc} --bfile $outdir/$name.merge.$refname \
      --pca \
      --out $outdir/$name.$reference
mv $outdir/$name.$reference.log $qcdir/plink_log


